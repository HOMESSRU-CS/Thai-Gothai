// ถ้าไม่มีพิกัดจริง ใช้พิกัดจังหวัด + เลื่อนเล็กน้อยให้หมุดไม่ทับกัน
export const getCoords = (place, index = 0) => {
  if (place.lat && place.lng) return [Number(place.lat), Number(place.lng)]
  const exact = placeCoords[place.name_th] || placeCoords[place.name]
  if (exact) return exact
  const base = provinceCoords[place.province]
  if (!base) return null
  const angle = index * 2.4, r = 0.06 + (index % 4) * 0.035
  return [base[0] + Math.sin(angle) * r, base[1] + Math.cos(angle) * r]
}
